// PLL (altpll, Cyclone IV E): clk_sys = inclk * MULT / DIV,
// clk_sdram = same frequency shifted by SDRAM_PHASE_PS, driven to DRAM_CLK.
module sdram_pll #(
  parameter int    INCLK_PERIOD_PS = 20000,    // 50 MHz
  parameter int    MULT            = 2,
  parameter int    DIV             = 1,
  parameter string SDRAM_PHASE_PS  = "-3000"
) (
  input  logic inclk,
  input  logic areset,
  output logic clk_sys,
  output logic clk_sdram,
  output logic locked
);

  wire [4:0] sub_clk;

  altpll #(
    .bandwidth_type          ("AUTO"),
    .clk0_divide_by          (DIV),
    .clk0_duty_cycle         (50),
    .clk0_multiply_by        (MULT),
    .clk0_phase_shift        ("0"),
    .clk1_divide_by          (DIV),
    .clk1_duty_cycle         (50),
    .clk1_multiply_by        (MULT),
    .clk1_phase_shift        (SDRAM_PHASE_PS),
    .compensate_clock        ("CLK0"),
    .inclk0_input_frequency  (INCLK_PERIOD_PS),
    .intended_device_family  ("Cyclone IV E"),
    .lpm_hint                ("CBX_MODULE_PREFIX=sdram_pll"),
    .lpm_type                ("altpll"),
    .operation_mode          ("NORMAL"),
    .pll_type                ("AUTO"),
    .port_activeclock        ("PORT_UNUSED"),
    .port_areset             ("PORT_USED"),
    .port_clkbad0            ("PORT_UNUSED"),
    .port_clkbad1            ("PORT_UNUSED"),
    .port_clkloss            ("PORT_UNUSED"),
    .port_clkswitch          ("PORT_UNUSED"),
    .port_configupdate       ("PORT_UNUSED"),
    .port_fbin               ("PORT_UNUSED"),
    .port_inclk0             ("PORT_USED"),
    .port_inclk1             ("PORT_UNUSED"),
    .port_locked             ("PORT_USED"),
    .port_pfdena             ("PORT_UNUSED"),
    .port_phasecounterselect ("PORT_UNUSED"),
    .port_phasedone          ("PORT_UNUSED"),
    .port_phasestep          ("PORT_UNUSED"),
    .port_phaseupdown        ("PORT_UNUSED"),
    .port_pllena             ("PORT_UNUSED"),
    .port_scanaclr           ("PORT_UNUSED"),
    .port_scanclk            ("PORT_UNUSED"),
    .port_scanclkena         ("PORT_UNUSED"),
    .port_scandata           ("PORT_UNUSED"),
    .port_scandataout        ("PORT_UNUSED"),
    .port_scandone           ("PORT_UNUSED"),
    .port_scanread           ("PORT_UNUSED"),
    .port_scanwrite          ("PORT_UNUSED"),
    .port_clk0               ("PORT_USED"),
    .port_clk1               ("PORT_USED"),
    .port_clk2               ("PORT_UNUSED"),
    .port_clk3               ("PORT_UNUSED"),
    .port_clk4               ("PORT_UNUSED"),
    .port_clk5               ("PORT_UNUSED"),
    .port_clkena0            ("PORT_UNUSED"),
    .port_clkena1            ("PORT_UNUSED"),
    .port_clkena2            ("PORT_UNUSED"),
    .port_clkena3            ("PORT_UNUSED"),
    .port_clkena4            ("PORT_UNUSED"),
    .port_clkena5            ("PORT_UNUSED"),
    .port_extclk0            ("PORT_UNUSED"),
    .port_extclk1            ("PORT_UNUSED"),
    .port_extclk2            ("PORT_UNUSED"),
    .port_extclk3            ("PORT_UNUSED"),
    .self_reset_on_loss_lock ("OFF"),
    .width_clock             (5)
  ) altpll_component (
    .areset             (areset),
    .inclk              ({1'b0, inclk}),
    .clk                (sub_clk),
    .locked             (locked),
    .activeclock        (),
    .clkbad             (),
    .clkena             ({6{1'b1}}),
    .clkloss            (),
    .clkswitch          (1'b0),
    .configupdate       (1'b0),
    .enable0            (),
    .enable1            (),
    .extclk             (),
    .extclkena          ({4{1'b1}}),
    .fbin               (1'b1),
    .fbmimicbidir       (),
    .fbout              (),
    .fref               (),
    .icdrclk            (),
    .pfdena             (1'b1),
    .phasecounterselect ({4{1'b1}}),
    .phasedone          (),
    .phasestep          (1'b1),
    .phaseupdown        (1'b1),
    .pllena             (1'b1),
    .scanaclr           (1'b0),
    .scanclk            (1'b0),
    .scanclkena         (1'b1),
    .scandata           (1'b0),
    .scandataout        (),
    .scandone           (),
    .scanread           (1'b0),
    .scanwrite          (1'b0),
    .sclkout0           (),
    .sclkout1           (),
    .vcooverrange       (),
    .vcounderrange      ()
  );

  assign clk_sys   = sub_clk[0];
  assign clk_sdram = sub_clk[1];

endmodule
